# ---- GM handbook PDF: Typst, two columns ----
# Pandoc turns the markdown into Typst; build.py adds page breaks, art, and wide tables.
# Art markers, invisible in the markdown:
#   <!-- art 40x50 right: what -->  spot art in a column; the text up to the next heading or table wraps around it
#                                   (mm; 80+ wide fills the column, no wrap)
#   <!-- art full 50: what -->      band across both columns, floated to the top or bottom of its page
#   <!-- pagebreak -->            before a heading: start it on a new page (both handbooks)
#   <!-- art fill -->             before a heading: that section sits at the bottom of the right column, fill art above
#   <!-- edge: what -->             strip in the outer margin on every page of this section
import pypandoc, typst
def raw(t): return f'\n\n```{{=typst}}\n{t}\n```\n\n'
def lit(t): return '"' + t.replace('\\', '\\\\').replace('"', '\\"') + '"'
def cells(t):
    """Split a Typst table body into its [cell] contents (brackets nest)."""
    out, depth = [], 0
    for ch in t:
        if ch == '[':
            depth += 1
            if depth == 1: out.append(''); continue
        elif ch == ']':
            depth -= 1
            if depth == 0: continue
        if depth: out[-1] += ch
    return out
def to_typ(md):
    t = pypandoc.convert_text(md, 'typst', format='markdown-auto_identifiers+raw_attribute', extra_args=['--wrap=none'])
    # Column widths from content: short columns hug their text, the rest share the slack by average length.
    def table(m):
        n = m[1].count('%') or int(m[1])
        cs = [re.sub(r'#\w+\[|\\', '', c) for c in cells(m[3])]
        cols = [cs[i::n] for i in range(n)]
        spec = ', '.join('auto' if max(map(len, c)) <= 8 else f'{sum(map(len, c)) / len(c):.0f}fr' for c in cols)
        return f'#table(\n    columns: ({spec},),\n    align: ({m[2].replace("auto", "left")}),{m[3]}'
    t = re.sub(r'#table\(\n\s*columns: \(?([^)\n]*?)\)?,\n\s*align: \(([^)]*)\),(.*?)\n\s*\)\]', lambda m: table(m) + ')]', t, flags=re.S)
    return t
md = open('GM-HANDBOOK.md').read()
md = re.sub(r'([ᛄ∵ϟ△⌘]) (Seron|Orvik|Zhark|Drun|Veyra)', '\\1\u00a0\\2', md)
# <!-- pagebreak --> before a heading: new page, and a section for the page-count check.
md = re.sub(r'^<!-- pagebreak -->\n\n(#+ (.+))$', lambda m: raw(f'#fence({lit(m[2])})') + m[1], md, flags=re.M)
def wide(m):
    # Mid-section subheading or bare table (no page break above): sink to page bottom so it stays after the text before it.
    where = 'bottom' if m[0].startswith(('####', '|')) and not m.string[:m.start()].endswith('```\n\n') else 'auto'
    return raw(f'#place({where}, float: true, scope: "parent", clearance: 10pt, block(width: 100%)[#set align(left)') + m[0] + raw('])')
# A pipe table with 6+ columns, plus the blocks before it back to its heading (if no other table or art sits between).
md = re.sub(r'(?:^#+ [^\n]*\n\n(?:(?![|#<`])[^\n]+\n\n)*)?^\|(?:[^|\n]*\|){6,}\n(?:\|[^\n]*\n)+', wide, md, flags=re.M)
md = re.sub(r'(#fence\(.*?\)\n```\n\n)(#+ [^\n]+)\n', lambda m: m[1] + raw('#place(top, float: true, scope: "parent", clearance: 10pt, block(width: 100%)[#set align(left)') + m[2] + raw('])'), md)
md = md.replace('<!-- art fill -->', raw('#fill-above()'))
md = re.sub(r'<!-- edge: (.*?) -->', lambda m: raw(f'#edge({lit(m[1])})'), md)
md = re.sub(r'<!-- art full (\d+): (.*?) -->', lambda m: raw(f'#art-wide({m[1]}, {lit(m[2])})'), md)
def spot(m):
    w, h, side, what, body = m[1], m[2], m[3], m[4], m[5]
    box = f'art-box({w}, {h}, {lit(what)})'
    if int(w) >= 80: return raw('#' + box) + body
    return raw(f'#wrap-content({box}, align: {side})[\n{to_typ(body)}\n]')
md = re.sub(r'<!-- art (\d+)x(\d+) (left|right): (.*?) -->\n\n(.*?)(?=\n\n(?:#|\||<!--|```)|\Z)', spot, md, flags=re.S)
