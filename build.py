def fill(name, content):
    global sheet
    sheet, n = re.subn(rf'(<!-- {name}:start -->).*?(<!-- {name}:end -->)',
                       lambda m: m[1] + '\n' + content + '\n' + m[2], sheet, flags=re.S)
    assert n == 1, f'{SHEET}: marker {name} not found'
fill('guide-nav', '\n'.join(nav))
